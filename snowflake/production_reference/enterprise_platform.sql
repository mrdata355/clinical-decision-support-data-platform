-- Clinical Decision Support Data Platform — enterprise Snowflake reference
-- Portfolio/reference implementation informed by publicly described clinical decision-support
-- product patterns. Generated/de-identified data only; no real patient data is included.
--
-- Review order:
--   1. Schemas / control tables
--   2. Immutable RAW landing
--   3. Normalized STAGING contracts
--   4. Conformed CORE dimensions/facts
--   5. MART serving layer
--   6. FEATURES / MLOps offline features
--   7. GOVERNANCE / lineage
--   8. Streams / merge / operational views

