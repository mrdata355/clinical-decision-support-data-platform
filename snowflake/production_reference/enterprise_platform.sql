-- FEATURES — OFFLINE FEATURE PRODUCTS
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW FEATURES.TOOL_RECOMMENDATION_DAILY AS
SELECT
    EVENT_DATE,USER_TOKEN,TOOL_ID,PRIMARY_SPECIALTY,CHANNEL,
    COUNT_IF(EVENT_TYPE='tool_view') OVER(PARTITION BY USER_TOKEN,TOOL_ID ORDER BY EVENT_DATE ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) USER_TOOL_VIEWS_28D,
    COUNT_IF(EVENT_TYPE='tool_complete') OVER(PARTITION BY USER_TOKEN,TOOL_ID ORDER BY EVENT_DATE ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) USER_TOOL_COMPLETIONS_28D,
    COUNT_IF(EVENT_TYPE='favorite_add') OVER(PARTITION BY USER_TOKEN,TOOL_ID ORDER BY EVENT_DATE ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) USER_TOOL_FAVORITES_28D,
    MAX(EVENT_TS) OVER(PARTITION BY USER_TOKEN,TOOL_ID ORDER BY EVENT_DATE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) LAST_USER_TOOL_EVENT_TS
FROM CORE.FCT_PRODUCT_EVENT
WHERE USER_TOKEN IS NOT NULL AND TOOL_ID IS NOT NULL;

CREATE OR REPLACE VIEW FEATURES.EHR_AUTOFILL_FIELD_DAILY AS
SELECT
    EVENT_DATE,INTEGRATION_ID,TOOL_ID,CONFIDENCE_BAND,
    SUM(COALESCE(AUTOFILL_FIELD_COUNT,0)) AUTOFILL_FIELD_COUNT,
    SUM(COALESCE(AUTOFILL_CONFIRMED_COUNT,0)) CONFIRMED_FIELD_COUNT,
    DIV0(SUM(COALESCE(AUTOFILL_CONFIRMED_COUNT,0)),SUM(COALESCE(AUTOFILL_FIELD_COUNT,0))) CONFIRMATION_RATE
FROM CORE.FCT_PRODUCT_EVENT
WHERE EVENT_TYPE='ehr_autofill'
GROUP BY 1,2,3,4;

CREATE OR REPLACE VIEW FEATURES.PIPELINE_RUN_FEATURE AS
SELECT
    RUN_ID,PIPELINE_NAME,STARTED_AT,COMPLETED_AT,SOURCE_COUNT,ACCEPTED_COUNT,QUARANTINED_COUNT,
    DUPLICATE_COUNT,STALE_COUNT,PUBLISHED_COUNT,
    DIV0(QUARANTINED_COUNT,SOURCE_COUNT) QUARANTINE_RATIO,
    DIV0(DUPLICATE_COUNT,SOURCE_COUNT) DUPLICATE_RATIO,
    DIV0(STALE_COUNT,SOURCE_COUNT) STALE_RATIO,
    DATEDIFF('second',STARTED_AT,COMPLETED_AT) DURATION_SECONDS,
    IFF(STATUS='SUCCESS',0,1) FAILURE_LABEL
FROM OPS.PIPELINE_RUN;

