CREATE OR REPLACE VIEW OPS.V_PIPELINE_HEALTH AS
SELECT
    PIPELINE_NAME,
    MAX_BY(RUN_ID,STARTED_AT) LAST_RUN_ID,
    MAX(STARTED_AT) LAST_STARTED_AT,
    MAX(COMPLETED_AT) LAST_COMPLETED_AT,
    MAX_BY(STATUS,STARTED_AT) LAST_STATUS,
    MAX_BY(SOURCE_COUNT,STARTED_AT) LAST_SOURCE_COUNT,
    MAX_BY(QUARANTINED_COUNT,STARTED_AT) LAST_QUARANTINED_COUNT,
    MAX_BY(PUBLISHED_COUNT,STARTED_AT) LAST_PUBLISHED_COUNT,
    DATEDIFF('minute',MAX(COMPLETED_AT),CURRENT_TIMESTAMP()) MINUTES_SINCE_COMPLETION,
    COUNT_IF(STARTED_AT>=DATEADD('hour',-24,CURRENT_TIMESTAMP()) AND STATUS<>'SUCCESS') FAILURES_24H
FROM OPS.PIPELINE_RUN
GROUP BY PIPELINE_NAME;

CREATE OR REPLACE VIEW OPS.V_RECONCILIATION_HEALTH AS
SELECT
    RUN_ID,
    COUNT(*) CONTROL_COUNT,
    COUNT_IF(STATUS='PASS') PASS_COUNT,
    COUNT_IF(STATUS='WARN') WARN_COUNT,
    COUNT_IF(STATUS='FAIL') FAIL_COUNT,
    MAX(ABS(DIFFERENCE_VALUE)) MAX_ABS_DIFFERENCE,
    MAX(CHECKED_AT) LAST_CHECKED_AT
FROM OPS.RECONCILIATION_RESULT
GROUP BY RUN_ID;

CREATE OR REPLACE VIEW OPS.V_MODEL_HEALTH AS
SELECT
    MODEL_NAME,MODEL_VERSION,
    MAX(METRIC_TS) LAST_METRIC_AT,
    SUM(REQUEST_COUNT) REQUESTS,
    SUM(ERROR_COUNT) ERRORS,
    DIV0(SUM(ERROR_COUNT),SUM(REQUEST_COUNT)) ERROR_RATE,
    MAX_BY(P95_LATENCY_MS,METRIC_TS) LATEST_P95_LATENCY_MS,
    MAX_BY(FEATURE_DRIFT_SCORE,METRIC_TS) LATEST_FEATURE_DRIFT_SCORE,
    MAX_BY(LABEL_METRIC_NAME,METRIC_TS) LATEST_LABEL_METRIC_NAME,
    MAX_BY(LABEL_METRIC_VALUE,METRIC_TS) LATEST_LABEL_METRIC_VALUE
FROM OPS.MODEL_SERVICE_METRIC
WHERE METRIC_TS>=DATEADD('day',-7,CURRENT_TIMESTAMP())
GROUP BY 1,2;

