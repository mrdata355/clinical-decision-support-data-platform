CREATE OR REPLACE PROCEDURE OPS.MERGE_PRODUCT_EVENTS()
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
    MERGE INTO CORE.FCT_PRODUCT_EVENT T
    USING (
      SELECT
        S.EVENT_ID,S.EVENT_TYPE,S.EVENT_TS,TO_DATE(S.EVENT_TS) EVENT_DATE,S.BUSINESS_KEY,S.SESSION_ID,
        S.TOOL_ID,CT.CLINICAL_TOOL_KEY,CT.PRIMARY_SPECIALTY,CT.CONDITION_GROUP,CT.TOOL_TYPE,
        S.CONTENT_ID,C.CONTENT_KEY,S.QUALITY_RATING_ID,S.ACCOUNT_TOKEN,A.ACCOUNT_KEY,S.USER_TOKEN,S.ORGANIZATION_TOKEN,
        S.CHANNEL,S.COUNTRY_CODE,S.LANGUAGE_CODE,S.INTEGRATION_ID,S.SEARCH_QUERY_TOKEN,S.SEARCH_RESULT_RANK,
        S.COMPLETION_ID,S.RESULT_BAND,S.INPUT_COUNT,S.AUTOFILL_FIELD_COUNT,S.AUTOFILL_CONFIRMED_COUNT,
        S.CONFIDENCE_BAND,S.RECOMMENDATION_MODEL,S.RECOMMENDATION_POSITION,S.CME_CREDIT_HOURS,S.EXPERIMENT_ASSIGNMENTS,
        S.SOURCE_SYSTEM,S.SOURCE_VERSION,S.SOURCE_UPDATED_AT,S.CANONICAL_HASH
      FROM STAGING.PRODUCT_EVENT_STREAM S
      LEFT JOIN CORE.DIM_CLINICAL_TOOL CT ON S.TOOL_ID=CT.TOOL_ID AND CT.IS_CURRENT
      LEFT JOIN CORE.DIM_CONTENT C ON S.CONTENT_ID=C.CONTENT_ID AND C.IS_CURRENT
      LEFT JOIN CORE.DIM_ACCOUNT A ON S.ACCOUNT_TOKEN=A.ACCOUNT_TOKEN
      QUALIFY ROW_NUMBER() OVER(PARTITION BY S.EVENT_ID ORDER BY S.SOURCE_VERSION DESC,S.SOURCE_UPDATED_AT DESC)=1
    ) S
    ON T.EVENT_ID=S.EVENT_ID
    WHEN MATCHED AND (
      S.SOURCE_VERSION>T.SOURCE_VERSION OR
      (S.SOURCE_VERSION=T.SOURCE_VERSION AND S.SOURCE_UPDATED_AT>T.SOURCE_UPDATED_AT AND S.CANONICAL_HASH<>T.CANONICAL_HASH)
    ) THEN UPDATE SET
      EVENT_TYPE=S.EVENT_TYPE,EVENT_TS=S.EVENT_TS,EVENT_DATE=S.EVENT_DATE,BUSINESS_KEY=S.BUSINESS_KEY,SESSION_ID=S.SESSION_ID,
      TOOL_ID=S.TOOL_ID,CLINICAL_TOOL_KEY=S.CLINICAL_TOOL_KEY,PRIMARY_SPECIALTY=S.PRIMARY_SPECIALTY,CONDITION_GROUP=S.CONDITION_GROUP,
      TOOL_TYPE=S.TOOL_TYPE,CONTENT_ID=S.CONTENT_ID,CONTENT_KEY=S.CONTENT_KEY,QUALITY_RATING_ID=S.QUALITY_RATING_ID,
      ACCOUNT_TOKEN=S.ACCOUNT_TOKEN,ACCOUNT_KEY=S.ACCOUNT_KEY,USER_TOKEN=S.USER_TOKEN,ORGANIZATION_TOKEN=S.ORGANIZATION_TOKEN,
      CHANNEL=S.CHANNEL,COUNTRY_CODE=S.COUNTRY_CODE,LANGUAGE_CODE=S.LANGUAGE_CODE,INTEGRATION_ID=S.INTEGRATION_ID,
      SEARCH_QUERY_TOKEN=S.SEARCH_QUERY_TOKEN,SEARCH_RESULT_RANK=S.SEARCH_RESULT_RANK,COMPLETION_ID=S.COMPLETION_ID,
      RESULT_BAND=S.RESULT_BAND,INPUT_COUNT=S.INPUT_COUNT,AUTOFILL_FIELD_COUNT=S.AUTOFILL_FIELD_COUNT,
      AUTOFILL_CONFIRMED_COUNT=S.AUTOFILL_CONFIRMED_COUNT,CONFIDENCE_BAND=S.CONFIDENCE_BAND,
      RECOMMENDATION_MODEL=S.RECOMMENDATION_MODEL,RECOMMENDATION_POSITION=S.RECOMMENDATION_POSITION,CME_CREDIT_HOURS=S.CME_CREDIT_HOURS,
      EXPERIMENT_ASSIGNMENTS=S.EXPERIMENT_ASSIGNMENTS,SOURCE_SYSTEM=S.SOURCE_SYSTEM,SOURCE_VERSION=S.SOURCE_VERSION,
      SOURCE_UPDATED_AT=S.SOURCE_UPDATED_AT,CANONICAL_HASH=S.CANONICAL_HASH,UPDATED_AT=CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT(
      EVENT_ID,EVENT_TYPE,EVENT_TS,EVENT_DATE,BUSINESS_KEY,SESSION_ID,TOOL_ID,CLINICAL_TOOL_KEY,PRIMARY_SPECIALTY,CONDITION_GROUP,
      TOOL_TYPE,CONTENT_ID,CONTENT_KEY,QUALITY_RATING_ID,ACCOUNT_TOKEN,ACCOUNT_KEY,USER_TOKEN,ORGANIZATION_TOKEN,CHANNEL,
      COUNTRY_CODE,LANGUAGE_CODE,INTEGRATION_ID,SEARCH_QUERY_TOKEN,SEARCH_RESULT_RANK,COMPLETION_ID,RESULT_BAND,INPUT_COUNT,
      AUTOFILL_FIELD_COUNT,AUTOFILL_CONFIRMED_COUNT,CONFIDENCE_BAND,RECOMMENDATION_MODEL,RECOMMENDATION_POSITION,CME_CREDIT_HOURS,
      EXPERIMENT_ASSIGNMENTS,SOURCE_SYSTEM,SOURCE_VERSION,SOURCE_UPDATED_AT,CANONICAL_HASH
    ) VALUES(
      S.EVENT_ID,S.EVENT_TYPE,S.EVENT_TS,S.EVENT_DATE,S.BUSINESS_KEY,S.SESSION_ID,S.TOOL_ID,S.CLINICAL_TOOL_KEY,S.PRIMARY_SPECIALTY,S.CONDITION_GROUP,
      S.TOOL_TYPE,S.CONTENT_ID,S.CONTENT_KEY,S.QUALITY_RATING_ID,S.ACCOUNT_TOKEN,S.ACCOUNT_KEY,S.USER_TOKEN,S.ORGANIZATION_TOKEN,S.CHANNEL,
      S.COUNTRY_CODE,S.LANGUAGE_CODE,S.INTEGRATION_ID,S.SEARCH_QUERY_TOKEN,S.SEARCH_RESULT_RANK,S.COMPLETION_ID,S.RESULT_BAND,S.INPUT_COUNT,
      S.AUTOFILL_FIELD_COUNT,S.AUTOFILL_CONFIRMED_COUNT,S.CONFIDENCE_BAND,S.RECOMMENDATION_MODEL,S.RECOMMENDATION_POSITION,S.CME_CREDIT_HOURS,
      S.EXPERIMENT_ASSIGNMENTS,S.SOURCE_SYSTEM,S.SOURCE_VERSION,S.SOURCE_UPDATED_AT,S.CANONICAL_HASH
    );

    RETURN OBJECT_CONSTRUCT('status','MERGED','rows_affected',SQLROWCOUNT,'merged_at',CURRENT_TIMESTAMP());
END;
$$;

