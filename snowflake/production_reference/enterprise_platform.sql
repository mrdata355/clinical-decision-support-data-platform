-- -----------------------------------------------------------------------------
-- MART — GOVERNED SERVING MODELS
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW MART.V_PRODUCT_DAILY AS
SELECT
    EVENT_DATE,CHANNEL,COUNTRY_CODE,
    COUNT_IF(EVENT_TYPE='session_start') SESSIONS_STARTED,
    COUNT_IF(EVENT_TYPE='search') SEARCHES,
    COUNT_IF(EVENT_TYPE='search_result_click') SEARCH_RESULT_CLICKS,
    COUNT_IF(EVENT_TYPE='tool_view') TOOL_VIEWS,
    COUNT_IF(EVENT_TYPE='tool_start') TOOL_STARTS,
    COUNT_IF(EVENT_TYPE='tool_complete') TOOL_COMPLETIONS,
    COUNT_IF(EVENT_TYPE IN ('content_view','guideline_view','cme_content_view')) CONTENT_VIEWS,
    COUNT_IF(EVENT_TYPE='cme_credit_earned') CME_CREDIT_EVENTS,
    SUM(IFF(EVENT_TYPE='cme_credit_earned',COALESCE(CME_CREDIT_HOURS,0),0)) CME_CREDIT_HOURS,
    COUNT(DISTINCT USER_TOKEN) UNIQUE_USERS,
    COUNT(DISTINCT ACCOUNT_KEY) UNIQUE_ACCOUNTS,
    DIV0(COUNT_IF(EVENT_TYPE='tool_complete'),COUNT_IF(EVENT_TYPE='tool_start')) COMPLETION_RATE
FROM CORE.FCT_PRODUCT_EVENT
GROUP BY 1,2,3;

CREATE OR REPLACE VIEW MART.V_TOOL_ENGAGEMENT_DAILY AS
SELECT
    E.EVENT_DATE,E.TOOL_ID,T.TOOL_NAME,T.PRIMARY_SPECIALTY,E.CHANNEL,E.COUNTRY_CODE,
    COUNT_IF(E.EVENT_TYPE='tool_view') VIEWS,
    COUNT_IF(E.EVENT_TYPE='tool_start') STARTS,
    COUNT_IF(E.EVENT_TYPE='tool_complete') COMPLETIONS,
    COUNT_IF(E.EVENT_TYPE='favorite_add') FAVORITE_ADDS,
    COUNT(DISTINCT E.USER_TOKEN) UNIQUE_USERS,
    COUNT(DISTINCT E.SESSION_ID) SESSIONS,
    DIV0(COUNT_IF(E.EVENT_TYPE='tool_start'),COUNT_IF(E.EVENT_TYPE='tool_view')) START_RATE,
    DIV0(COUNT_IF(E.EVENT_TYPE='tool_complete'),COUNT_IF(E.EVENT_TYPE='tool_start')) COMPLETION_RATE
FROM CORE.FCT_PRODUCT_EVENT E
LEFT JOIN CORE.DIM_CLINICAL_TOOL T ON E.CLINICAL_TOOL_KEY=T.CLINICAL_TOOL_KEY
GROUP BY 1,2,3,4,5,6;

CREATE OR REPLACE VIEW MART.V_EHR_INTEGRATION_DAILY AS
SELECT
    EVENT_DATE,COALESCE(INTEGRATION_ID,'unknown') INTEGRATION_ID,
    COUNT_IF(EVENT_TYPE='integration_launch') LAUNCHES,
    COUNT_IF(EVENT_TYPE='ehr_context_open') CONTEXT_OPENS,
    COUNT_IF(EVENT_TYPE='ehr_autofill') AUTOFILL_EVENTS,
    COUNT_IF(EVENT_TYPE='ehr_result_writeback') WRITEBACKS,
    SUM(COALESCE(AUTOFILL_FIELD_COUNT,0)) AUTOFILL_FIELDS,
    SUM(COALESCE(AUTOFILL_CONFIRMED_COUNT,0)) CONFIRMED_FIELDS,
    DIV0(SUM(COALESCE(AUTOFILL_CONFIRMED_COUNT,0)),SUM(COALESCE(AUTOFILL_FIELD_COUNT,0))) CONFIRMATION_RATE,
    COUNT(DISTINCT TOOL_ID) UNIQUE_TOOLS,
    COUNT(DISTINCT ACCOUNT_KEY) UNIQUE_ACCOUNTS
FROM CORE.FCT_PRODUCT_EVENT
WHERE INTEGRATION_ID IS NOT NULL OR EVENT_TYPE LIKE 'ehr_%' OR EVENT_TYPE='integration_launch'
GROUP BY 1,2;

