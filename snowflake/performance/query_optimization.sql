-- Performance acceptance gate example: compare candidate query shapes against a stable baseline.
CREATE OR REPLACE VIEW OPS.V_PERFORMANCE_REGRESSION_CANDIDATES AS
SELECT
    QUERY_PARAMETERIZED_HASH,
    WAREHOUSE_NAME,
    EXECUTIONS,
    P95_SECONDS,
    P95_BYTES_SCANNED,
    AVG_PARTITION_SCAN_RATIO,
    TOTAL_REMOTE_SPILL_BYTES,
    CASE
      WHEN P95_SECONDS >= 10 OR TOTAL_REMOTE_SPILL_BYTES > 0 OR AVG_PARTITION_SCAN_RATIO > 0.80 THEN 'REVIEW'
      WHEN P95_SECONDS >= 5 OR AVG_PARTITION_SCAN_RATIO > 0.50 THEN 'WATCH'
      ELSE 'HEALTHY'
    END AS OPTIMIZATION_STATUS
FROM OPS.V_EXPENSIVE_QUERY_SHAPES;
