    START_TIME,
    END_TIME,
    WAREHOUSE_NAME,
    AVG_RUNNING,
    AVG_QUEUED_LOAD,
    AVG_QUEUED_PROVISIONING,
    AVG_BLOCKED
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_LOAD_HISTORY
WHERE START_TIME >= DATEADD('day',-7,CURRENT_TIMESTAMP())
  AND WAREHOUSE_NAME IN ('INGEST_WH','TRANSFORM_WH','BI_WH');

