CREATE OR REPLACE DYNAMIC TABLE MART.DT_LIVE_TOOL_FUNNEL
  TARGET_LAG='1 minute'
  WAREHOUSE=BI_WH
  REFRESH_MODE=INCREMENTAL
  INITIALIZE=ON_CREATE
AS
SELECT
  E.EVENT_DATE,
  E.TOOL_ID,
  T.TOOL_NAME,
  T.PRIMARY_SPECIALTY,
  E.CHANNEL,
  E.COUNTRY_CODE,
  COUNT_IF(E.EVENT_TYPE='tool_view') AS TOOL_VIEWS,
  COUNT_IF(E.EVENT_TYPE='tool_start') AS TOOL_STARTS,
  COUNT_IF(E.EVENT_TYPE='tool_complete') AS TOOL_COMPLETIONS,
  COUNT_IF(E.EVENT_TYPE='favorite_add') AS FAVORITE_ADDS,
  COUNT(DISTINCT E.USER_TOKEN) AS UNIQUE_USERS,
  COUNT(DISTINCT E.SESSION_ID) AS SESSIONS,
  DIV0(COUNT_IF(E.EVENT_TYPE='tool_start'),COUNT_IF(E.EVENT_TYPE='tool_view')) AS VIEW_TO_START_RATE,
  DIV0(COUNT_IF(E.EVENT_TYPE='tool_complete'),COUNT_IF(E.EVENT_TYPE='tool_start')) AS START_TO_COMPLETE_RATE
FROM CORE.FCT_PRODUCT_EVENT E
LEFT JOIN CORE.DIM_CLINICAL_TOOL T
  ON E.CLINICAL_TOOL_KEY=T.CLINICAL_TOOL_KEY
WHERE E.EVENT_TS >= DATEADD('day',-2,CURRENT_TIMESTAMP())
GROUP BY 1,2,3,4,5,6;

CREATE OR REPLACE DYNAMIC TABLE MART.DT_LIVE_SEARCH_DISCOVERY
  TARGET_LAG='1 minute'
  WAREHOUSE=BI_WH
  REFRESH_MODE=INCREMENTAL
  INITIALIZE=ON_CREATE
AS
SELECT
  EVENT_DATE,
  CHANNEL,
  COUNTRY_CODE,
  COUNT_IF(EVENT_TYPE='search') SEARCHES,
  COUNT_IF(EVENT_TYPE='search_result_click') SEARCH_RESULT_CLICKS,
  COUNT_IF(EVENT_TYPE='tool_view') TOOL_VIEWS,
  COUNT_IF(EVENT_TYPE='tool_complete') TOOL_COMPLETIONS,
  COUNT(DISTINCT SEARCH_QUERY_TOKEN) UNIQUE_QUERY_TOKENS,
  COUNT(DISTINCT USER_TOKEN) UNIQUE_USERS
FROM CORE.FCT_PRODUCT_EVENT
WHERE EVENT_TS >= DATEADD('day',-2,CURRENT_TIMESTAMP())
GROUP BY 1,2,3;

CREATE OR REPLACE DYNAMIC TABLE MART.DT_LIVE_EHR_INTEGRATION
  TARGET_LAG='1 minute'
  WAREHOUSE=BI_WH
  REFRESH_MODE=INCREMENTAL
  INITIALIZE=ON_CREATE
AS
SELECT
  EVENT_DATE,
  COALESCE(INTEGRATION_ID,'unknown') INTEGRATION_ID,
  COUNT_IF(EVENT_TYPE='integration_launch') LAUNCHES,
  COUNT_IF(EVENT_TYPE='ehr_context_open') CONTEXT_OPENS,
  COUNT_IF(EVENT_TYPE='ehr_autofill') AUTOFILL_EVENTS,
  COUNT_IF(EVENT_TYPE='ehr_result_writeback') WRITEBACKS,
  SUM(COALESCE(AUTOFILL_FIELD_COUNT,0)) AUTOFILL_FIELDS,
  SUM(COALESCE(AUTOFILL_CONFIRMED_COUNT,0)) CONFIRMED_FIELDS,
  DIV0(SUM(COALESCE(AUTOFILL_CONFIRMED_COUNT,0)),SUM(COALESCE(AUTOFILL_FIELD_COUNT,0))) CONFIRMATION_RATE,
  COUNT(DISTINCT TOOL_ID) UNIQUE_TOOLS,
  COUNT(DISTINCT ACCOUNT_KEY) UNIQUE_ACCOUNTS
FROM CORE.FCT_PRODUCT_EVENT
WHERE EVENT_TS >= DATEADD('day',-2,CURRENT_TIMESTAMP())
  AND (INTEGRATION_ID IS NOT NULL OR EVENT_TYPE LIKE 'ehr_%' OR EVENT_TYPE='integration_launch')
GROUP BY 1,2;

CREATE OR REPLACE DYNAMIC TABLE OPS.DT_CONTINUOUS_PIPELINE_SLO
  TARGET_LAG='2 minutes'
  WAREHOUSE=BI_WH
  REFRESH_MODE=INCREMENTAL
  INITIALIZE=ON_CREATE
AS
SELECT
  PIPELINE_NAME,
  MAX_BY(RUN_ID,STARTED_AT) LAST_RUN_ID,
  MAX(STARTED_AT) LAST_STARTED_AT,
  MAX(COMPLETED_AT) LAST_COMPLETED_AT,
  MAX_BY(STATUS,STARTED_AT) LAST_STATUS,
  MAX_BY(SOURCE_COUNT,STARTED_AT) LAST_SOURCE_COUNT,
  MAX_BY(QUARANTINED_COUNT,STARTED_AT) LAST_QUARANTINED_COUNT,
  DATEDIFF('second',MAX(COMPLETED_AT),CURRENT_TIMESTAMP()) FRESHNESS_SECONDS,
  DIV0(MAX_BY(QUARANTINED_COUNT,STARTED_AT),NULLIF(MAX_BY(SOURCE_COUNT,STARTED_AT),0)) QUARANTINE_RATIO,
  COUNT_IF(STARTED_AT >= DATEADD('hour',-24,CURRENT_TIMESTAMP()) AND STATUS<>'SUCCESS') FAILURES_24H
FROM OPS.PIPELINE_RUN
GROUP BY PIPELINE_NAME;

-- Dynamic-table refresh diagnostics: useful for continuous-query SLO evidence.
CREATE OR REPLACE VIEW OPS.V_DYNAMIC_TABLE_REFRESH_HEALTH AS
SELECT
  NAME,
  SCHEMA_NAME,
  DATABASE_NAME,
  STATE,
  REFRESH_START_TIME,
  REFRESH_END_TIME,
  COMPLETION_TARGET,
  DATA_TIMESTAMP,
  DATEDIFF('second',DATA_TIMESTAMP,CURRENT_TIMESTAMP()) DATA_AGE_SECONDS,
  REFRESH_ACTION,
  REFRESH_TRIGGER,
  ERROR_CODE,
  ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(
  DATE_RANGE_START=>DATEADD('hour',-24,CURRENT_TIMESTAMP()),
  DATE_RANGE_END=>CURRENT_TIMESTAMP()
));

-- -----------------------------------------------------------------------------
-- PERIODIC QUALITY SNAPSHOT
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TASK OPS.TASK_PIPELINE_HEALTH_SNAPSHOT
  WAREHOUSE=BI_WH
  SCHEDULE='USING CRON */15 * * * * UTC'
  ALLOW_OVERLAPPING_EXECUTION=FALSE
AS
INSERT INTO OPS.DATA_QUALITY_RESULT(
  RUN_ID,MODEL_NAME,TEST_NAME,SEVERITY,STATUS,FAILED_ROWS,TOTAL_ROWS,FAILURE_RATIO,DETAILS
)
SELECT
  UUID_STRING(),
  'OPS.DT_CONTINUOUS_PIPELINE_SLO',
  'continuous_freshness_snapshot',
  'ERROR',
  IFF(COUNT_IF(FRESHNESS_SECONDS>3600 OR LAST_STATUS<>'SUCCESS')=0,'PASS','FAIL'),
  COUNT_IF(FRESHNESS_SECONDS>3600 OR LAST_STATUS<>'SUCCESS'),
  COUNT(*),
  DIV0(COUNT_IF(FRESHNESS_SECONDS>3600 OR LAST_STATUS<>'SUCCESS'),COUNT(*)),
  OBJECT_CONSTRUCT('captured_at',CURRENT_TIMESTAMP(),'max_freshness_seconds',3600)
FROM OPS.DT_CONTINUOUS_PIPELINE_SLO;

