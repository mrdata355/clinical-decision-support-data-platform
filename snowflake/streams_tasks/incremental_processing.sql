CREATE OR REPLACE TASK OPS.TASK_REFRESH_SESSION_FACT
  WAREHOUSE=TRANSFORM_WH
  AFTER OPS.TASK_MERGE_PRODUCT_EVENTS
AS
MERGE INTO CORE.FCT_SESSION T
USING (
  SELECT
    SESSION_ID,
    TO_DATE(MIN(EVENT_TS)) SESSION_DATE,
    MAX(ACCOUNT_KEY) ACCOUNT_KEY,
    MAX(USER_TOKEN) USER_TOKEN,
    MAX(CHANNEL) CHANNEL,
    MAX(COUNTRY_CODE) COUNTRY_CODE,
    MIN(EVENT_TS) STARTED_AT,
    MAX(EVENT_TS) ENDED_AT,
    DATEDIFF('second',MIN(EVENT_TS),MAX(EVENT_TS)) DURATION_SECONDS,
    COUNT_IF(EVENT_TYPE='tool_view') TOOL_VIEWS,
    COUNT_IF(EVENT_TYPE='tool_start') TOOL_STARTS,
    COUNT_IF(EVENT_TYPE='tool_complete') TOOL_COMPLETIONS,
    COUNT_IF(EVENT_TYPE='search') SEARCHES,
    COUNT_IF(EVENT_TYPE IN ('content_view','guideline_view','cme_content_view')) CONTENT_VIEWS,
    MIN_BY(EVENT_ID,EVENT_TS) FIRST_EVENT_ID,
    MAX_BY(EVENT_ID,EVENT_TS) LAST_EVENT_ID
  FROM CORE.FCT_PRODUCT_EVENT
  WHERE SESSION_ID IS NOT NULL
    AND EVENT_TS>=DATEADD('day',-2,CURRENT_TIMESTAMP())
  GROUP BY SESSION_ID
) S
ON T.SESSION_ID=S.SESSION_ID
WHEN MATCHED THEN UPDATE SET
  SESSION_DATE=S.SESSION_DATE,
  ACCOUNT_KEY=S.ACCOUNT_KEY,
  USER_TOKEN=S.USER_TOKEN,
  CHANNEL=S.CHANNEL,
  COUNTRY_CODE=S.COUNTRY_CODE,
  STARTED_AT=S.STARTED_AT,
  ENDED_AT=S.ENDED_AT,
  DURATION_SECONDS=S.DURATION_SECONDS,
  TOOL_VIEWS=S.TOOL_VIEWS,
  TOOL_STARTS=S.TOOL_STARTS,
  TOOL_COMPLETIONS=S.TOOL_COMPLETIONS,
  SEARCHES=S.SEARCHES,
  CONTENT_VIEWS=S.CONTENT_VIEWS,
  FIRST_EVENT_ID=S.FIRST_EVENT_ID,
  LAST_EVENT_ID=S.LAST_EVENT_ID,
  UPDATED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT(
  SESSION_ID,SESSION_DATE,ACCOUNT_KEY,USER_TOKEN,CHANNEL,COUNTRY_CODE,STARTED_AT,
  ENDED_AT,DURATION_SECONDS,TOOL_VIEWS,TOOL_STARTS,TOOL_COMPLETIONS,SEARCHES,
  CONTENT_VIEWS,FIRST_EVENT_ID,LAST_EVENT_ID,UPDATED_AT
) VALUES(
  S.SESSION_ID,S.SESSION_DATE,S.ACCOUNT_KEY,S.USER_TOKEN,S.CHANNEL,S.COUNTRY_CODE,S.STARTED_AT,
  S.ENDED_AT,S.DURATION_SECONDS,S.TOOL_VIEWS,S.TOOL_STARTS,S.TOOL_COMPLETIONS,S.SEARCHES,
  S.CONTENT_VIEWS,S.FIRST_EVENT_ID,S.LAST_EVENT_ID,CURRENT_TIMESTAMP()
);

