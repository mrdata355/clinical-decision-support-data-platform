ON TABLE RAW.CLINICAL_TOOL_SNAPSHOT
APPEND_ONLY=TRUE
COMMENT='Versioned clinical tool metadata awaiting conformance';

CREATE STREAM IF NOT EXISTS RAW.CONTENT_SNAPSHOT_STREAM
ON TABLE RAW.CONTENT_SNAPSHOT
APPEND_ONLY=TRUE
COMMENT='Guideline/editorial/CME content metadata awaiting conformance';

CREATE STREAM IF NOT EXISTS RAW.QUALITY_RATING_SNAPSHOT_STREAM
ON TABLE RAW.QUALITY_RATING_SNAPSHOT
APPEND_ONLY=TRUE
COMMENT='Reference quality-rating updates awaiting conformance';

