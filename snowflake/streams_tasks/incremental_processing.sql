ON TABLE STAGING.PRODUCT_EVENT
APPEND_ONLY=TRUE
COMMENT='Normalized events awaiting canonical fact merge';

-- -----------------------------------------------------------------------------
-- PRODUCT EVENT NORMALIZATION
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TASK OPS.TASK_NORMALIZE_PRODUCT_EVENTS
  WAREHOUSE=TRANSFORM_WH
  SCHEDULE='1 MINUTE'
  ALLOW_OVERLAPPING_EXECUTION=FALSE
  WHEN SYSTEM$STREAM_HAS_DATA('RAW.PRODUCT_EVENT_INGEST_STREAM')
AS
MERGE INTO STAGING.PRODUCT_EVENT T
USING (
  SELECT
    EVENT_ID,
    LOWER(EVENT_TYPE) EVENT_TYPE,
    EVENT_TS,
    SOURCE_UPDATED_AT,
    SOURCE_SYSTEM,
    COALESCE(PAYLOAD:source_version::NUMBER,1) SOURCE_VERSION,
    COALESCE(BUSINESS_KEY,EVENT_ID) BUSINESS_KEY,
    PAYLOAD:session_id::STRING SESSION_ID,
    PAYLOAD:tool_id::STRING TOOL_ID,
    PAYLOAD:content_id::STRING CONTENT_ID,
    PAYLOAD:quality_rating_id::STRING QUALITY_RATING_ID,
    COALESCE(PAYLOAD:account_token::STRING,PAYLOAD:account_id_token::STRING) ACCOUNT_TOKEN,
    COALESCE(PAYLOAD:user_token::STRING,PAYLOAD:user_id_token::STRING) USER_TOKEN,
    PAYLOAD:organization_token::STRING ORGANIZATION_TOKEN,
    LOWER(COALESCE(PAYLOAD:channel::STRING,'web')) CHANNEL,
    UPPER(COALESCE(PAYLOAD:country_code::STRING,'ZZ')) COUNTRY_CODE,
    LOWER(PAYLOAD:language_code::STRING) LANGUAGE_CODE,
    PAYLOAD:integration_id::STRING INTEGRATION_ID,
    PAYLOAD:query_token::STRING SEARCH_QUERY_TOKEN,
    TRY_TO_NUMBER(PAYLOAD:search_result_rank::STRING) SEARCH_RESULT_RANK,
    PAYLOAD:completion_id::STRING COMPLETION_ID,
    PAYLOAD:result_band::STRING RESULT_BAND,
    TRY_TO_NUMBER(PAYLOAD:input_count::STRING) INPUT_COUNT,
    TRY_TO_NUMBER(PAYLOAD:autofill_field_count::STRING) AUTOFILL_FIELD_COUNT,
    TRY_TO_NUMBER(PAYLOAD:autofill_confirmed_count::STRING) AUTOFILL_CONFIRMED_COUNT,
    PAYLOAD:confidence_band::STRING CONFIDENCE_BAND,
    PAYLOAD:recommendation_model::STRING RECOMMENDATION_MODEL,
    TRY_TO_NUMBER(PAYLOAD:recommendation_position::STRING) RECOMMENDATION_POSITION,
    TRY_TO_DOUBLE(PAYLOAD:cme_credit_hours::STRING) CME_CREDIT_HOURS,
    PAYLOAD:experiment_assignments EXPERIMENT_ASSIGNMENTS,
    SHA2(TO_JSON(PAYLOAD),256) CANONICAL_HASH
  FROM RAW.PRODUCT_EVENT_INGEST_STREAM
  WHERE EVENT_ID IS NOT NULL
    AND EVENT_TYPE IS NOT NULL
    AND EVENT_TS IS NOT NULL
    AND SOURCE_UPDATED_AT IS NOT NULL
  QUALIFY ROW_NUMBER() OVER(
    PARTITION BY EVENT_ID
    ORDER BY COALESCE(PAYLOAD:source_version::NUMBER,1) DESC,
             SOURCE_UPDATED_AT DESC,
             INGESTED_AT DESC
  )=1
) S
ON T.EVENT_ID=S.EVENT_ID
WHEN MATCHED AND (
  S.SOURCE_VERSION>T.SOURCE_VERSION OR
  (S.SOURCE_VERSION=T.SOURCE_VERSION AND S.SOURCE_UPDATED_AT>T.SOURCE_UPDATED_AT)
) THEN UPDATE SET
  EVENT_TYPE=S.EVENT_TYPE,
  EVENT_TS=S.EVENT_TS,
  SOURCE_UPDATED_AT=S.SOURCE_UPDATED_AT,
  SOURCE_SYSTEM=S.SOURCE_SYSTEM,
  SOURCE_VERSION=S.SOURCE_VERSION,
  BUSINESS_KEY=S.BUSINESS_KEY,
  SESSION_ID=S.SESSION_ID,
  TOOL_ID=S.TOOL_ID,
  CONTENT_ID=S.CONTENT_ID,
  QUALITY_RATING_ID=S.QUALITY_RATING_ID,
  ACCOUNT_TOKEN=S.ACCOUNT_TOKEN,
  USER_TOKEN=S.USER_TOKEN,
  ORGANIZATION_TOKEN=S.ORGANIZATION_TOKEN,
  CHANNEL=S.CHANNEL,
  COUNTRY_CODE=S.COUNTRY_CODE,
  LANGUAGE_CODE=S.LANGUAGE_CODE,
  INTEGRATION_ID=S.INTEGRATION_ID,
  SEARCH_QUERY_TOKEN=S.SEARCH_QUERY_TOKEN,
  SEARCH_RESULT_RANK=S.SEARCH_RESULT_RANK,
  COMPLETION_ID=S.COMPLETION_ID,
  RESULT_BAND=S.RESULT_BAND,
  INPUT_COUNT=S.INPUT_COUNT,
  AUTOFILL_FIELD_COUNT=S.AUTOFILL_FIELD_COUNT,
  AUTOFILL_CONFIRMED_COUNT=S.AUTOFILL_CONFIRMED_COUNT,
  CONFIDENCE_BAND=S.CONFIDENCE_BAND,
  RECOMMENDATION_MODEL=S.RECOMMENDATION_MODEL,
  RECOMMENDATION_POSITION=S.RECOMMENDATION_POSITION,
  CME_CREDIT_HOURS=S.CME_CREDIT_HOURS,
  EXPERIMENT_ASSIGNMENTS=S.EXPERIMENT_ASSIGNMENTS,
  CANONICAL_HASH=S.CANONICAL_HASH,
  NORMALIZED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT(
  EVENT_ID,EVENT_TYPE,EVENT_TS,SOURCE_UPDATED_AT,SOURCE_SYSTEM,SOURCE_VERSION,
  BUSINESS_KEY,SESSION_ID,TOOL_ID,CONTENT_ID,QUALITY_RATING_ID,ACCOUNT_TOKEN,USER_TOKEN,
  ORGANIZATION_TOKEN,CHANNEL,COUNTRY_CODE,LANGUAGE_CODE,INTEGRATION_ID,SEARCH_QUERY_TOKEN,
  SEARCH_RESULT_RANK,COMPLETION_ID,RESULT_BAND,INPUT_COUNT,AUTOFILL_FIELD_COUNT,
  AUTOFILL_CONFIRMED_COUNT,CONFIDENCE_BAND,RECOMMENDATION_MODEL,RECOMMENDATION_POSITION,
  CME_CREDIT_HOURS,EXPERIMENT_ASSIGNMENTS,CANONICAL_HASH,NORMALIZED_AT
) VALUES(
  S.EVENT_ID,S.EVENT_TYPE,S.EVENT_TS,S.SOURCE_UPDATED_AT,S.SOURCE_SYSTEM,S.SOURCE_VERSION,
  S.BUSINESS_KEY,S.SESSION_ID,S.TOOL_ID,S.CONTENT_ID,S.QUALITY_RATING_ID,S.ACCOUNT_TOKEN,S.USER_TOKEN,
  S.ORGANIZATION_TOKEN,S.CHANNEL,S.COUNTRY_CODE,S.LANGUAGE_CODE,S.INTEGRATION_ID,S.SEARCH_QUERY_TOKEN,
  S.SEARCH_RESULT_RANK,S.COMPLETION_ID,S.RESULT_BAND,S.INPUT_COUNT,S.AUTOFILL_FIELD_COUNT,
  S.AUTOFILL_CONFIRMED_COUNT,S.CONFIDENCE_BAND,S.RECOMMENDATION_MODEL,S.RECOMMENDATION_POSITION,
  S.CME_CREDIT_HOURS,S.EXPERIMENT_ASSIGNMENTS,S.CANONICAL_HASH,CURRENT_TIMESTAMP()
);

